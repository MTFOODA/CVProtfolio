/// Delivery routing: PDFs keep the `printing` route, DOCX must never reach a
/// receiver announced as a PDF.
///
/// `printing` 5.15.1 hard-codes `application/pdf` in its Android share intent,
/// which is why Android delivers DOCX through `FilePicker.saveFile` — an
/// `ACTION_CREATE_DOCUMENT` intent whose media type the plugin derives from the
/// `.docx` extension through the platform's `MimeTypeMap`.
library;

import 'package:archive/archive.dart';
import 'package:flutter/foundation.dart';
import 'package:flutter_test/flutter_test.dart';

import 'package:cv_portfolio_maker/core/domain/document_entity.dart';
import 'package:cv_portfolio_maker/core/domain/document_models.dart';
import 'package:cv_portfolio_maker/core/domain/enums.dart';
import 'package:cv_portfolio_maker/core/domain/profile_models.dart';
import 'package:cv_portfolio_maker/core/export/export_delivery.dart';
import 'package:cv_portfolio_maker/core/export/export_fonts.dart';
import 'package:cv_portfolio_maker/core/export/export_service.dart';
import 'package:cv_portfolio_maker/features/export/export_sheet.dart';

/// One call made through the save seam.
typedef SaveCall = ({Uint8List bytes, String fileName, String mimeType});

/// One call made through the share seam.
typedef ShareCall = ({Uint8List bytes, String filename});

/// An [ExportDelivery] whose platform seams record instead of executing.
class FakeDelivery {
  FakeDelivery({this.pickerSupported = true});

  /// What the platform predicate reports.
  final bool pickerSupported;

  /// Every save the delivery asked for, in order.
  final List<SaveCall> saved = [];

  /// Every share/download the delivery asked for, in order.
  final List<ShareCall> shares = [];

  /// What the save seam returns; `null` means "the picker was dismissed".
  Uri? saveReturn = Uri.parse('content://com.android.documents/document/1');

  /// What the share seam returns; `false` means "the dialog was dismissed".
  bool shareReturn = true;

  /// When set, the save seam throws it instead of saving.
  Object? saveThrows;

  /// When set, the share seam throws it instead of sharing.
  Object? shareThrows;

  late final ExportDelivery delivery = ExportDelivery(
    sharePdf: ({required Uint8List bytes, required String filename}) async {
      final error = shareThrows;
      if (error != null) throw error;
      shares.add((bytes: bytes, filename: filename));
      return shareReturn;
    },
    saveFile:
        ({
          required String fileName,
          required Uint8List bytes,
          required String mimeType,
        }) async {
          final error = saveThrows;
          if (error != null) throw error;
          saved.add((bytes: bytes, fileName: fileName, mimeType: mimeType));
          return saveReturn;
        },
    usesDocumentPicker: () => pickerSupported,
  );
}

/// A fake Android platform, where the document picker is required.
FakeDelivery androidDelivery() => FakeDelivery();

/// A fake non-Android platform, where the existing share route is kept.
FakeDelivery sharingDelivery() => FakeDelivery(pickerSupported: false);

/// A document with the sections the deliveries are exercised with.
CvDocument _document() => CvDocument(
  id: 'doc-1',
  ownerId: 'u1',
  title: 'Ada Lovelace',
  design: DocumentDesign(
    sections: const [
      SectionConfig(id: 'experience', kind: SectionKind.experience),
      SectionConfig(id: 'skills', kind: SectionKind.skills),
    ],
  ),
);

/// A profile with enough content that the DOCX export is valid.
UserProfile _profile() => UserProfile(
  id: 'u1',
  details: ProfileDetails(
    fullName: 'Ada Lovelace',
    professionalTitle: 'Mathematician',
    email: 'ada@example.com',
    summary: 'Mathematician and writer.',
  ),
  experiences: const [
    ExperienceEntry(
      id: 'e1',
      company: 'Analytical Engines Ltd',
      position: 'Lead Analyst',
      descriptions: ['Designed the first published algorithm.'],
    ),
  ],
  skills: const [SkillEntry(id: 's1', name: 'Mathematics')],
  projects: const [],
);

void main() {
  group('docx media type', () {
    test('is the OOXML WordprocessingML type, never a PDF type', () {
      expect(
        docxMimeType,
        'application/vnd.openxmlformats-officedocument.'
        'wordprocessingml.document',
      );
      expect(docxMimeType, isNot('application/pdf'));
      expect(docxMimeType, startsWith('application/vnd.openxmlformats-'));
    });
  });

  group('DOCX on Android', () {
    test('saves the generated bytes with the DOCX media type', () async {
      final fake = androidDelivery();
      final bytes = Uint8List.fromList(List<int>.generate(64, (i) => i));
      const fileName = 'Ada Lovelace-Editable.docx';

      final outcome = await fake.delivery.saveDocument(bytes, fileName);

      expect(outcome.completed, isTrue);
      expect(outcome.cancelled, isFalse);
      expect(fake.saved, hasLength(1));
      expect(fake.saved.single.mimeType, docxMimeType);
      expect(fake.saved.single.fileName, fileName);
      expect(fake.saved.single.fileName, endsWith('.docx'));
      // Identical instance: the payload is never re-encoded on the way out.
      expect(identical(fake.saved.single.bytes, bytes), isTrue);
      expect(fake.saved.single.bytes, orderedEquals(bytes));
    });

    test('never uses the PDF share route for a DOCX', () async {
      final fake = androidDelivery();

      await fake.delivery.saveDocument(Uint8List(8), 'Ada-Editable.docx');

      expect(fake.shares, isEmpty);
    });

    test('a dismissed picker is cancelled, never success', () async {
      final fake = androidDelivery()..saveReturn = null;

      final outcome = await fake.delivery.saveDocument(
        Uint8List(8),
        'Ada-Editable.docx',
      );

      expect(outcome.completed, isFalse);
      expect(outcome.cancelled, isTrue);
      expect(deliveryMessageKey(outcome), 'exportShareCancelled');
    });

    test('a failed save is reported as failure, never success', () async {
      final fake = androidDelivery()
        ..saveThrows = StateError('no document provider');

      final outcome = await fake.delivery.saveDocument(
        Uint8List(8),
        'Ada-Editable.docx',
      );

      expect(outcome.completed, isFalse);
      expect(outcome.cancelled, isFalse);
      expect(deliveryMessageKey(outcome), 'exportShareFailed');
    });
  });

  group('DOCX on every other platform', () {
    test('keeps the existing share route and payload', () async {
      final fake = sharingDelivery();
      final bytes = Uint8List.fromList(<int>[9, 8, 7]);

      final outcome = await fake.delivery.saveDocument(
        bytes,
        'Ada-Editable.docx',
      );

      expect(outcome.completed, isTrue);
      expect(fake.saved, isEmpty);
      expect(fake.shares, hasLength(1));
      expect(fake.shares.single.filename, 'Ada-Editable.docx');
      expect(identical(fake.shares.single.bytes, bytes), isTrue);
    });

    test('a dismissed share is cancelled, never success', () async {
      final fake = sharingDelivery()..shareReturn = false;

      final outcome = await fake.delivery.saveDocument(
        Uint8List(8),
        'Ada-Editable.docx',
      );

      expect(outcome.completed, isFalse);
      expect(outcome.cancelled, isTrue);
      expect(deliveryMessageKey(outcome), 'exportShareCancelled');
    });

    test('a failed share is reported as failure', () async {
      final fake = sharingDelivery()..shareThrows = StateError('no target');

      final outcome = await fake.delivery.saveDocument(
        Uint8List(8),
        'Ada-Editable.docx',
      );

      expect(outcome.completed, isFalse);
      expect(outcome.cancelled, isFalse);
      expect(deliveryMessageKey(outcome), 'exportShareFailed');
    });
  });
  group('PDF delivery is unchanged', () {
    test('share hands the exact PDF payload to Printing.sharePdf', () async {
      final fake = sharingDelivery();
      final bytes = Uint8List.fromList('%PDF-1.7'.codeUnits);

      final outcome = await fake.delivery.share(bytes, 'Ada-Designed.pdf');

      expect(outcome.completed, isTrue);
      expect(fake.shares, hasLength(1));
      expect(fake.shares.single.filename, 'Ada-Designed.pdf');
      expect(identical(fake.shares.single.bytes, bytes), isTrue);
      expect(fake.saved, isEmpty);
    });

    test('dismissal and failure keep their distinct outcomes', () async {
      final dismissed = sharingDelivery()..shareReturn = false;
      final dismissedOutcome = await dismissed.delivery.share(
        Uint8List(4),
        'Ada-Designed.pdf',
      );
      expect(dismissedOutcome.completed, isFalse);
      expect(dismissedOutcome.cancelled, isTrue);

      final failed = sharingDelivery()..shareThrows = StateError('boom');
      final failedOutcome = await failed.delivery.share(
        Uint8List(4),
        'Ada-Designed.pdf',
      );
      expect(failedOutcome.completed, isFalse);
      expect(failedOutcome.cancelled, isFalse);
      expect(deliveryMessageKey(failedOutcome), 'exportShareFailed');
    });

    test('a PDF is never routed through the save seam', () async {
      final fake = androidDelivery();

      await fake.delivery.share(Uint8List(4), 'Ada-Designed.pdf');

      expect(fake.saved, isEmpty);
      expect(fake.shares, hasLength(1));
    });
  });

  group('platform routing', () {
    tearDown(() => debugDefaultTargetPlatformOverride = null);

    test('Android uses the document picker for DOCX', () {
      debugDefaultTargetPlatformOverride = TargetPlatform.android;

      expect(const ExportDelivery().usesDocumentPicker(), isTrue);
    });

    test('every other platform keeps the share route', () {
      for (final platform in <TargetPlatform>[
        TargetPlatform.iOS,
        TargetPlatform.macOS,
        TargetPlatform.windows,
        TargetPlatform.linux,
        TargetPlatform.fuchsia,
      ]) {
        debugDefaultTargetPlatformOverride = platform;

        expect(
          const ExportDelivery().usesDocumentPicker(),
          isFalse,
          reason: '$platform must keep the existing share route',
        );
      }
    });
  });

  group('genuine payload', () {
    test('the DOCX offered to a receiver is a real OOXML package', () async {
      final exporter = DocumentExporter(fonts: const BaseFontSource());
      final result = await exporter.exportDocx(
        document: _document(),
        profile: _profile(),
        languageCode: 'en',
      );

      expect(result.fileName, endsWith('.docx'));
      expect(result.fileName, docxFileName('Ada Lovelace'));

      final fake = androidDelivery();
      final outcome = await fake.delivery.saveDocument(
        result.bytes,
        result.fileName,
      );
      expect(outcome.completed, isTrue);

      final delivered = fake.saved.single.bytes;
      expect(fake.saved.single.mimeType, docxMimeType);
      expect(delivered.length, greaterThan(2000));
      // Not PDF bytes wearing a .docx name.
      expect(String.fromCharCodes(delivered.sublist(0, 5)), isNot('%PDF-'));
      expect(delivered.sublist(0, 4), <int>[0x50, 0x4B, 0x03, 0x04]);

      final archive = ZipDecoder().decodeBytes(delivered);
      final parts = archive.files.map((file) => file.name).toSet();
      expect(
        parts,
        containsAll(<String>[
          '[Content_Types].xml',
          '_rels/.rels',
          'word/document.xml',
        ]),
      );
    });
  });
}
