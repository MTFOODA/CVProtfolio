SkillIconOption skillIcon(String id) => skillIcons.firstWhere(
  (option) => option.id == id,
  orElse: () => skillIcons.first,
);

String _skillKey(String value) =>
    value.toLowerCase().replaceAll(RegExp(r'[^a-z0-9+#\u0620-\u064a]'), '');
List<SkillIconOption> matchingSkillIcons(String query) {
  final key = _skillKey(query);
  if (key.isEmpty) return skillIcons;
  final matches = skillIcons
      .where(
        (option) => [
          option.label,
          option.id,
          ...option.aliases,
        ].any((value) => _skillKey(value).contains(key)),
      )
      .toList();
  matches.sort((a, b) {
    bool exact(SkillIconOption item) => [
      item.label,
      item.id,
      ...item.aliases,
    ].any((value) => _skillKey(value) == key);
    return (exact(b) ? 1 : 0).compareTo(exact(a) ? 1 : 0);
  });
  return matches;
}

SkillIconOption? exactSkillIcon(String value) {
  final key = _skillKey(value);
  if (key.isEmpty) return null;
  for (final icon in skillIcons) {
    if ([
      icon.label,
      icon.id,
      ...icon.aliases,
    ].any((name) => _skillKey(name) == key)) {
      return icon;
    }
  }
  return null;
}

class SkillIconView extends StatelessWidget {
  const SkillIconView(this.id, {super.key, this.size = 24, this.color});
  final String id;
  final double size;
  final Color? color;
  @override
  Widget build(BuildContext context) {
    final option = skillIcon(id);
    return Semantics(
      label: option.label,
      child: option.monogram == null
          ? Icon(option.icon, size: size, color: color)
          : SizedBox.square(
              dimension: size,
              child: FittedBox(
                child: Text(
                  option.monogram!,
                  style: TextStyle(
                    fontFamily: 'inter',
                    fontWeight: FontWeight.w600,
                    color: color ?? IconTheme.of(context).color,
                  ),
                ),
              ),
            ),
    );
  }
}
